import JSZip from "jszip";
import type { BibleBook } from "../../../domain/BibleBook";
import { getBookIdByUsfmCode } from "../../../versification/UsfmBookCodes";
import { EPUB_IMPORT_LIMITS, normalizeZipPath, readZipText, validateZipArchive } from "../../epub/EpubContainerReader";
import { EpubImportError } from "../../epub/EpubImportError";
import { findElementsByName, parseHtmlDocument } from "../../epub/MarkupDocument";
import { assertBibleImportNotAborted, createBibleImportTimeSlicer } from "../BibleImportCancellation";
import { BibleIndexBuilder, normalizeLanguage } from "../BibleIndexBuilder";
import { BibleImportInput, BibleImportOptions, BibleImportResult, BibleSource, BibleSourceFile, BibleSourceMetadata } from "../BibleSource";
import { readAllXhtmlDocuments } from "../EpubBibleDocuments";
import { normalizeInline } from "../dbs-html/dbsHtml";
import { detectLanguageFromBookNames, findTraditionalBookAbbreviations } from "../ebible-epub/bookAbbreviationTables";
import { DBS_ARCHIVE_BOOK_FILE_PATTERN, extractBookNamesFromArchiveIndex, extractVersesFromAlephDocument } from "./dbsAlephHtml";

const INDEX_FILE_PATTERN = /(?:^|\/)index\.html$/;

/**
 * HTML archive of the Digital Bible Society (bibles.dbs.org, "html_<ID>.zip"), generated by Aleph: one page
 * per book, the books in the order of the index page. The archive names neither the translation nor its
 * language: the name defaults to the archive name, the language is guessed from the book names.
 * Books outside the 66-book canon are skipped.
 */
export class DbsHtmlArchiveBibleSource implements BibleSource {
    readonly id = "dbs-html-archive";
    readonly label = "dbs.org (HTML ZIP)";
    readonly fileTypes = { extensions: [".zip"], mimeTypes: ["application/zip"] };
    readonly maxFileBytes = EPUB_IMPORT_LIMITS.maxArchiveBytes;

    // Aleph signs every page with `<meta name="generator" content="Aleph …">`; one canonical book page is checked.
    async canHandle(file: BibleSourceFile): Promise<boolean> {
        const bytes = new Uint8Array(file.content.slice(0, 2));
        if (bytes[0] !== 0x50 || bytes[1] !== 0x4b || file.content.byteLength > this.maxFileBytes) {
            return false;
        }
        try {
            const zip = await JSZip.loadAsync(file.content);
            validateZipArchive(zip);
            const bookPath = Object.keys(zip.files).find((path) => isCanonicalBookFile(path));
            if (bookPath === undefined) {
                return false;
            }
            const html = await readZipText(zip, bookPath, EPUB_IMPORT_LIMITS.maxSingleHtmlTextBytes);
            return /<meta[^>]+name="generator"[^>]+content="Aleph\b/i.test(html);
        } catch {
            return false;
        }
    }

    async readMetadata(content: ArrayBuffer): Promise<BibleSourceMetadata> {
        const zip = await JSZip.loadAsync(content);
        validateZipArchive(zip);
        const index = await readIndex(zip);
        const books = getCanonicalBooks(zip, index.bookNames).map((book) => ({ id: book.bookId, name: book.name ?? book.code }));
        return { title: index.title, language: detectLanguageFromBookNames(books) };
    }

    async importBible(input: BibleImportInput, options: BibleImportOptions = {}): Promise<BibleImportResult> {
        assertBibleImportNotAborted(options);
        options.onProgress?.({ stage: "loading-zip", processedCount: 0, totalCount: 1 });
        const zip = await JSZip.loadAsync(input.content);
        assertBibleImportNotAborted(options);
        options.onProgress?.({ stage: "loading-zip", processedCount: 1, totalCount: 1 });
        validateZipArchive(zip);

        const index = await readIndex(zip);
        const bookFiles = getCanonicalBooks(zip, index.bookNames);
        if (bookFiles.length === 0) {
            throw new EpubImportError("The archive does not contain books of the 66-book canon.");
        }
        const skippedCodes = getBookCodes(zip).filter((code) => getBookIdByUsfmCode(code) === null);

        const documents = await readAllXhtmlDocuments(zip, bookFiles.map((book) => book.path), options);
        const htmlByPath = new Map(documents.map((document) => [document.path, document.html]));
        const pages = new Map(bookFiles.map((book) => [book.path, parseHtmlDocument(htmlByPath.get(book.path) ?? "")]));

        const namedBooks = bookFiles.map((book) => ({ id: book.bookId, name: book.name ?? readPageTitle(pages.get(book.path)) ?? book.code }));
        const language = normalizeLanguage(input.language) || detectLanguageFromBookNames(namedBooks) || "und";
        const translationName = input.translationName.trim() || index.title || input.fileName.replace(/\.zip$/i, "").replace(/^html_/i, "");
        const abbreviations = findTraditionalBookAbbreviations(language, namedBooks);
        const books: BibleBook[] = namedBooks.map((book) => ({ ...book, abbreviation: abbreviations.get(book.id) ?? book.name }));

        const builder = new BibleIndexBuilder({
            translationId: input.translationId,
            translationName,
            language,
            sourceFileName: input.fileName,
        }, options);
        builder.setBooks(books);
        if (skippedCodes.length > 0) {
            builder.addWarning(`Skipped books outside the 66-book canon: ${skippedCodes.join(", ")}`);
        }

        const yieldIfSliceElapsed = createBibleImportTimeSlicer();
        options.onProgress?.({ stage: "extracting-verses", processedCount: 0, totalCount: bookFiles.length });
        for (let bookIndex = 0; bookIndex < bookFiles.length; bookIndex += 1) {
            assertBibleImportNotAborted(options);
            const { path, code, bookId } = bookFiles[bookIndex];
            const page = pages.get(path);
            const verses = page === undefined ? [] : extractVersesFromAlephDocument(page, 0);
            if (verses.length === 0) {
                builder.addWarning(`No verses found in ${code}: ${path}`);
            }
            await builder.appendVerses(bookId, verses);
            options.onProgress?.({ stage: "extracting-verses", processedCount: bookIndex + 1, totalCount: bookFiles.length });
            await yieldIfSliceElapsed();
        }

        return builder.build();
    }
}

type ArchiveIndex = {
    title: string | null;
    bookNames: Map<string, string>;
};

type BookFile = {
    path: string;
    code: string;
    bookId: number;
    name: string | null;
};

async function readIndex(zip: JSZip): Promise<ArchiveIndex> {
    // The index page of the archive is the shortest path among the index pages (`html/index.html`).
    const indexPath = Object.keys(zip.files)
        .filter((path) => INDEX_FILE_PATTERN.test(path) && !zip.files[path].dir)
        .sort((left, right) => left.length - right.length)[0];
    if (indexPath === undefined) {
        return { title: null, bookNames: new Map() };
    }
    const document = parseHtmlDocument(await readZipText(zip, indexPath, EPUB_IMPORT_LIMITS.maxSingleHtmlTextBytes));
    return { title: readPageTitle(document), bookNames: extractBookNamesFromArchiveIndex(document) };
}

/** Canonical book pages in the order of the index page, then the others by book number. */
function getCanonicalBooks(zip: JSZip, bookNames: Map<string, string>): BookFile[] {
    const order = [...bookNames.keys()];
    const rank = (code: string): number => (order.includes(code) ? order.indexOf(code) : order.length);
    const books: BookFile[] = [];
    const seenBookIds = new Set<number>();

    for (const path of Object.keys(zip.files).map((value) => normalizeZipPath(value))) {
        const code = DBS_ARCHIVE_BOOK_FILE_PATTERN.exec(path)?.[1];
        const bookId = code === undefined ? null : getBookIdByUsfmCode(code);
        if (code === undefined || bookId === null || zip.files[path] === undefined || zip.files[path].dir || seenBookIds.has(bookId)) {
            continue;
        }
        seenBookIds.add(bookId);
        books.push({ path, code, bookId, name: bookNames.get(code) ?? null });
    }

    return books.sort((left, right) => rank(left.code) - rank(right.code) || left.bookId - right.bookId);
}

function getBookCodes(zip: JSZip): string[] {
    const codes = Object.keys(zip.files)
        .map((path) => DBS_ARCHIVE_BOOK_FILE_PATTERN.exec(path)?.[1])
        .filter((code): code is string => code !== undefined);
    return [...new Set(codes)].sort();
}

function isCanonicalBookFile(path: string): boolean {
    const code = DBS_ARCHIVE_BOOK_FILE_PATTERN.exec(path)?.[1];
    return code !== undefined && getBookIdByUsfmCode(code) !== null;
}

function readPageTitle(document: Document | undefined): string | null {
    const title = document === undefined ? "" : normalizeInline(findElementsByName(document, "title")[0]?.textContent ?? "");
    return title.length > 0 ? title : null;
}
