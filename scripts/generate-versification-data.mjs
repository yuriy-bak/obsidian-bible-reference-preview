// Generates src/versification/builtinVersificationData.ts from the Paratext .vrs files in
// src/versification/schemes (copied unchanged from sillsdev/machine.py, MIT).
// Keeps only the 66 canonical books: book lines and mappings whose both sides are canonical.
// Usage: node scripts/generate-versification-data.mjs [--check]
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMES_DIRECTORY = join(root, "src/versification/schemes");
const OUTPUT_PATH = join(root, "src/versification/builtinVersificationData.ts");

// Keep in sync with src/versification/UsfmBookCodes.ts.
const CANONICAL_BOOK_CODES = new Set([
  "GEN", "EXO", "LEV", "NUM", "DEU", "JOS", "JDG", "RUT", "1SA", "2SA",
  "1KI", "2KI", "1CH", "2CH", "EZR", "NEH", "EST", "JOB", "PSA", "PRO",
  "ECC", "SNG", "ISA", "JER", "LAM", "EZK", "DAN", "HOS", "JOL", "AMO",
  "OBA", "JON", "MIC", "NAM", "HAB", "ZEP", "HAG", "ZEC", "MAL",
  "MAT", "MRK", "LUK", "JHN", "ACT", "ROM", "1CO", "2CO", "GAL", "EPH",
  "PHP", "COL", "1TH", "2TH", "1TI", "2TI", "TIT", "PHM", "HEB", "JAS",
  "1PE", "2PE", "1JN", "2JN", "3JN", "JUD", "REV",
]);

// The Septuagint scheme has no DAN/EST lines: canonical Daniel and Esther are its Greek DAG/ESG.
const GREEK_BOOK_ALIASES = { DAG: "DAN", ESG: "EST" };

export const BUILTIN_SCHEMES = ["eng", "org", "lxx", "vul", "rsc"];

export function trimVrs(text) {
  let name = null;
  const sourceLines = [];

  for (const rawLine of text.split(/\r?\n/)) {
    const nameMatch = /^#\s*Versification\s+"([^"]+)"/.exec(rawLine);
    if (nameMatch !== null && name === null) {
      name = nameMatch[1];
    }

    // "#!" lines are active Paratext 7.3+ lines; the rest of "#" is a comment.
    let line = rawLine.trim();
    if (line.startsWith("#!")) {
      line = line.slice(2).trim();
    } else {
      line = line.split("#")[0].trim();
    }
    if (line !== "") {
      sourceLines.push(line);
    }
  }

  const definedBooks = new Set(sourceLines.filter((line) => !line.includes("=")).map((line) => line.split(/\s+/)[0]));
  const aliases = Object.fromEntries(Object.entries(GREEK_BOOK_ALIASES)
    .filter(([greek, canonical]) => definedBooks.has(greek) && !definedBooks.has(canonical)));
  const rename = (book) => aliases[book] ?? book;

  const lines = [];
  for (const line of sourceLines) {
    if (line.startsWith("-") || line.startsWith("*")) {
      // Excluded verses and verse segments are not used by the plugin.
      continue;
    }

    if (line.includes("=")) {
      const isManyToOne = line.startsWith("&");
      const [left, right] = (isManyToOne ? line.slice(1) : line).split("=").map((side) => side.trim());
      const [leftBook, ...leftRest] = left.split(/\s+/);
      const [rightBook] = right.split(/\s+/);
      if (!CANONICAL_BOOK_CODES.has(rename(leftBook)) || !CANONICAL_BOOK_CODES.has(rightBook)) {
        continue;
      }
      if (!/^[0-9A-Z]{3} \d+:\d+(-\d+)?$/.test(`${rename(leftBook)} ${leftRest.join(" ")}`) || !/^[0-9A-Z]{3} \d+:\d+(-\d+)?$/.test(right)) {
        continue;
      }
      lines.push(`${isManyToOne ? "&" : ""}${rename(leftBook)} ${leftRest.join(" ")} = ${right}`);
      continue;
    }

    const [book, ...chapters] = line.split(/\s+/);
    if (CANONICAL_BOOK_CODES.has(rename(book))) {
      lines.push([rename(book), ...chapters].join(" "));
    }
  }

  return { name: name ?? "", text: lines.join("\n") };
}

export async function generateVersificationData() {
  const entries = [];
  for (const id of BUILTIN_SCHEMES) {
    const { name, text } = trimVrs(await readFile(join(SCHEMES_DIRECTORY, `${id}.vrs`), "utf8"));
    entries.push(`    ${id}: {\n        name: ${JSON.stringify(name)},\n        vrs: ${JSON.stringify(text)},\n    },`);
  }

  const license = (await readFile(join(root, "THIRD_PARTY_NOTICES.md"), "utf8")).match(/```\n([\s\S]*?)\n```/)[1];
  return [
    "// Generated by scripts/generate-versification-data.mjs from src/versification/schemes/*.vrs. Do not edit.",
    // A "/*!" legal comment is kept by esbuild in main.js, as the MIT License of the data requires.
    "/*! Versification data from sillsdev/machine.py (https://github.com/sillsdev/machine.py)",
    ...license.split("\n").map((line) => ` * ${line}`.trimEnd()),
    " */",
    "export const BUILTIN_VERSIFICATION_DATA: Record<string, { name: string; vrs: string }> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = await generateVersificationData();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT_PATH, "utf8").catch(() => "");
    if (current !== generated) {
      console.error("builtinVersificationData.ts is out of date: run npm run generate:versification");
      process.exit(1);
    }
  } else {
    await writeFile(OUTPUT_PATH, generated);
    console.log(`Wrote ${OUTPUT_PATH} (${generated.length} bytes)`);
  }
}
