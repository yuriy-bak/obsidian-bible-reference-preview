const { assert, JSZip } = require("../helpers");
const {
  EbibleEpubBibleSource,
} = require("../../.test-build/src/infrastructure/sources/ebible-epub/EbibleEpubBibleSource.js");
const {
  extractVersesFromBookDocument,
} = require("../../.test-build/src/infrastructure/sources/ebible-epub/ebibleEpubHtml.js");
const {
  findTraditionalBookAbbreviations,
} = require("../../.test-build/src/infrastructure/sources/ebible-epub/bookAbbreviationTables.js");
const { parseXhtmlDocument } = require("../../.test-build/src/infrastructure/epub/MarkupDocument.js");
const { createBibleSources, selectBibleSource } = require("../../.test-build/src/infrastructure/sources/BibleSourceRegistry.js");

const xhtml = (body) => `<!DOCTYPE html><html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"><head><title>t</title></head><body>${body}</body></html>`;
const verses = (body) => extractVersesFromBookDocument(parseXhtmlDocument(xhtml(body)));
const verse = (id, number) => `<span class="verse" id="${id}">${number}&#160;</span>`;

// Markup of eBible.org EPUBs (Haiola), shaped after the Synodal, KJV and WEB files.
module.exports = async () => {
  // The id prefix of 1 Samuel ends with a digit: chapters come from the chapter labels, not from the verse ids.
  assert.deepStrictEqual(verses(`
    <ul class='tnav'><li><a href='1SA.xhtml#S11_0'>1</a></li><li><a href='1SA.xhtml#S110_0'>10</a></li></ul>
    <div class='main' id='S10_0'><div class='mt'>Первая книга Царств</div>
    <div class='psalmlabel' id='S11_0'> 1</div>
    <div class='p'>${verse("S11_1", 1)}Был один
      человек;  ${verse("S11_2", 2)}у него были две жены.</div>
    <div class='s'>Заголовок раздела</div>
    <div class='psalmlabel' id='S110_0'> 10</div>
    <div class='p'>${verse("S110_1", 1)}И взял Самуил сосуд с елеем.</div></div>`), [
    { chapter: 1, verse: 1, text: "Был один человек;", footnotes: [], paragraphStart: true },
    { chapter: 1, verse: 2, text: "у него были две жены.", footnotes: [], paragraphStart: false },
    { chapter: 10, verse: 1, text: "И взял Самуил сосуд с елеем.", footnotes: [], paragraphStart: true },
  ]);

  // Poetry lines break the verse, continuation paragraphs do not; footnotes are kept, cross references are not;
  // the KJV pilcrow marks a paragraph start.
  assert.deepStrictEqual(verses(`
    <div class='chapterlabel' id='JH1_0'>1</div>
    <div class='q'>${verse("JH1_1", 1)}Первая строка<a href='#FN1' epub:type='noteref' class='noteref'>*</a></div>
    <div class='q2'>вторая строка<a href='#FN2' epub:type='noteref' class='noteref'>†</a></div>
    <div class='m'>и продолжение.</div>
    <div class='b'></div>
    <div class='p'>конец. ${verse("JH1_2", 2)}¶ Новый абзац.</div>
    <aside epub:type='footnote' id="FN1"><p class="f"><a class="notebackref" href="#JH1_1"><span class="notemark">*</span> 1:1</a>
      <span class="ft">Или: «первая».</span></p></aside>
    <aside epub:type='footnote' id="FN2"><p class="x"><a class="notebackref" href="#JH1_1">†</a><span class="xt">Ин 3:16</span></p></aside>`), [
    { chapter: 1, verse: 1, text: "Первая строка\nвторая строка и продолжение.\nконец.", footnotes: ["Или: «первая»."], paragraphStart: true },
    { chapter: 1, verse: 2, text: "Новый абзац.", footnotes: [], paragraphStart: true },
  ]);

  // A one-chapter book without chapter labels: every verse id shares the whole stem, read as chapter 1.
  assert.deepStrictEqual(verses(`<div class='p'>${verse("JD1_1", 1)}Иуда, раб. ${verse("JD1_2", 2)}Милость вам.</div>`)
    .map(({ chapter, verse: number }) => [chapter, number]), [[1, 1], [1, 2]]);

  // Abbreviation tables apply only to names of their tradition: the NWT "1 Царей" is 1 Kings, 3 Kings of the Synodal one.
  const synodalNames = { 9: "Первая книга Царств", 11: "Третья книга Царств", 40: "Евангелие от Матфея", 49: "Послание к Ефесянам", 62: "Первое послание Иоанна" };
  const synodal = findTraditionalBookAbbreviations("ru", Object.entries(synodalNames).map(([id, name]) => ({ id: Number(id), name })));
  assert.deepStrictEqual([...synodal.values()], ["1Цар", "3Цар", "Мф", "Еф", "1Ин"]);
  const nwtLike = [{ id: 9, name: "1 Самуила" }, { id: 11, name: "1 Царей" }, { id: 40, name: "Матфея" }];
  assert.strictEqual(findTraditionalBookAbbreviations("ru", nwtLike).size, 0);
  assert.deepStrictEqual([...findTraditionalBookAbbreviations("en", [{ id: 9, name: "I Samuel" }, { id: 43, name: "John" }, { id: 62, name: "1 John" }]).values()],
    ["1 Sam", "John", "1 John"]);
  assert.strictEqual(findTraditionalBookAbbreviations("tr", [{ id: 43, name: "YUHANNA" }]).size, 0);

  // The whole file: recognized by the Haiola signature, books in spine order, other books skipped.
  const createEbibleEpub = async ({ signature = "ePub generated by Haiola" } = {}) => {
    const zip = new JSZip();
    zip.file("mimetype", "application/epub+zip");
    zip.file("META-INF/container.xml", `<?xml version="1.0"?><container xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles></container>`);
    const files = ["index.xhtml", "MAT.xhtml", "JAS.xhtml", "TOB.xhtml", "ROM.xhtml", "copyright.xhtml"];
    const manifest = files.map((href, index) => `<item id="f${index}" href="${href}" media-type="application/xhtml+xml"/>`).join("");
    const spine = files.map((_href, index) => `<itemref idref="f${index}"/>`).join("");
    zip.file("OEBPS/content.opf", `<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" version="3.0"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>Синодальный перевод</dc:title><dc:language>ru</dc:language></metadata><manifest>${manifest}</manifest><spine>${spine}</spine></package>`);
    zip.file("OEBPS/index.xhtml", xhtml(`<ul class='tnav'><li><a href='MAT.xhtml'>Евангелие от Матфея</a></li><li><a href='JAS.xhtml'>Послание Иакова</a></li><li><a href='TOB.xhtml'>Товит</a></li><li><a href='ROM.xhtml'>Послание к Римлянам</a></li></ul>`));
    zip.file("OEBPS/copyright.xhtml", xhtml(`<p>Public Domain</p><p>${signature}</p>`));
    zip.file("OEBPS/MAT.xhtml", xhtml(`<div class='chapterlabel' id='MT1_0'>1</div><div class='p'>${verse("MT1_1", 1)}Родословие Иисуса Христа.</div>`));
    zip.file("OEBPS/JAS.xhtml", xhtml(`<div class='chapterlabel' id='JM1_0'>1</div><div class='p'>${verse("JM1_1", 1)}Иаков, раб Бога.</div>`));
    zip.file("OEBPS/TOB.xhtml", xhtml(`<div class='p'>${verse("TB1_1", 1)}Книга слов Товита.</div>`));
    zip.file("OEBPS/ROM.xhtml", xhtml(`<div class='chapterlabel' id='RM1_0'>1</div><div class='p'>${verse("RM1_1", 1)}Павел, раб Иисуса Христа.</div>`));
    return zip.generateAsync({ type: "arraybuffer" });
  };

  const content = await createEbibleEpub();
  assert.strictEqual((await selectBibleSource(createBibleSources(), { fileName: "russyn.epub", content })).id, "ebible-epub");
  const source = new EbibleEpubBibleSource();
  assert.strictEqual(await source.canHandle({ fileName: "other.epub", content: await createEbibleEpub({ signature: "Made by hand" }) }), false);
  assert.deepStrictEqual(await source.readMetadata(content), { title: "Синодальный перевод", language: "ru" });

  const result = await source.importBible({ fileName: "russyn.epub", content, translationId: "ru-syn", translationName: "", language: "" });
  const translation = result.bibleIndexV2Data.translations["ru-syn"];
  assert.strictEqual(translation.name, "Синодальный перевод");
  assert.strictEqual(translation.language, "ru");
  assert.deepStrictEqual(translation.bookOrder, [40, 59, 45]);
  assert.deepStrictEqual(result.books.map((book) => [book.id, book.name, book.abbreviation]), [
    [40, "Евангелие от Матфея", "Мф"],
    [59, "Послание Иакова", "Иак"],
    [45, "Послание к Римлянам", "Рим"],
  ]);
  assert(result.warnings.includes("Skipped books outside the 66-book canon: TOB"), "skipped books warning");
  assert.strictEqual(result.compactBooks[translation.books["45"].path].chapters[1][1].text, "Павел, раб Иисуса Христа.");
  // Three verses cannot tell numbering schemes apart.
  assert.strictEqual(result.versificationDetection.confident, false);
  assert.strictEqual(result.versificationDetection.scores.length, 5);
};
