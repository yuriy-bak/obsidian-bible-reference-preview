const { assert, JSZip } = require("../helpers");
const { DbsEpubBibleSource } = require("../../.test-build/src/infrastructure/sources/dbs-aleph/DbsEpubBibleSource.js");
const { DbsHtmlArchiveBibleSource } = require("../../.test-build/src/infrastructure/sources/dbs-aleph/DbsHtmlArchiveBibleSource.js");
const { extractVersesFromAlephDocument } = require("../../.test-build/src/infrastructure/sources/dbs-aleph/dbsAlephHtml.js");
const { parseHtmlDocument, parseXhtmlDocument } = require("../../.test-build/src/infrastructure/epub/MarkupDocument.js");
const { createBibleSources, selectBibleSource } = require("../../.test-build/src/infrastructure/sources/BibleSourceRegistry.js");

// EPUB of dbs.org generated by Aleph, shaped after the GOST Romanized Synodal file (RUSSGOS); the paragraph
// and footnote markup follows its stylesheet (USFM classes, `a[role="doc-noteref"]`, `section[role="doc-endnotes"]`).
const xhtml = (title, body) => `<?xml version="1.0" encoding="UTF-8"?><html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"><head><title>${title}</title></head><body>${body}</body></html>`;
const verse = (sid, number) => `<sup class="v v${number}" data-verse="${number}" data-sid="${sid}" title="${sid}:${number}">${number}</sup>`;
const chapter = (number, content, notes = "") => `<div id="chapter_content"><h4 class="c">${number}</h4><b class="c c${number}" title="${number}">${number}</b>${content}<section role="doc-endnotes"><ol>${notes}</ol></section></div>`;
const verses = (number, content, notes) => extractVersesFromAlephDocument(parseXhtmlDocument(xhtml(`Bible | Book ${number}`, chapter(number, content, notes))), number);

module.exports = async () => {
  // Without paragraph markup each verse starts its own paragraph.
  assert.deepStrictEqual(verses(3, `${verse("JHN3", 1)}  Между фарисеями был
    некто, именем Никодим.
    ${verse("JHN3", 2)}  Он пришел к Иисусу ночью.`), [
    { chapter: 3, verse: 1, text: "Между фарисеями был некто, именем Никодим.", footnotes: [], paragraphStart: true },
    { chapter: 3, verse: 2, text: "Он пришел к Иисусу ночью.", footnotes: [], paragraphStart: true },
  ]);

  // A psalm title is plain text between the chapter labels and verse 1 in the EPUB: the heading of verse 1.
  assert.deepStrictEqual(extractVersesFromAlephDocument(parseXhtmlDocument(xhtml("Bible | Псалтирь 22",
    `<div id="chapter_content"><h4 class="c">22</h4>Псалом Давида.<b class="c c22" title="22">22</b>${verse("PSA22", 1)}  Господь - Пастырь мой;${verse("PSA22", 2)}  Он покоит меня.</div>`)), 22)
    .map((item) => [item.verse, item.heading]), [[1, "Псалом Давида."], [2, undefined]]);

  // Paragraphs and poetry lines are kept, headings are not verse text; footnotes come from the endnotes
  // without their back link and verse reference, cross references are left out; a range is a joined verse.
  const psalm = verses(3, `<p class="d">Псалом Давида.</p>`
    + `<p class="q1">${verse("PSA3", 2)} Господи! как умножились враги мои!<a role="doc-noteref" epub:type="noteref" href="#fn1" id="r1">a</a></p>`
    + `<p class="q2">многие восстают на меня<a role="doc-noteref" href="#x1">*</a></p>`
    + `<p class="s1">Заголовок</p>`
    + `<p class="p">${verse("PSA3", 3)} Многие говорят. ${verse("PSA3", "4-5")} Но Ты, Господи.</p>`
    + `<p class="m">${verse("PSA3", 6)} Ложусь я.</p>`,
    `<li id="fn1"><p><span class="fr">3:2 </span><span class="ft">Или: противники.</span> <a role="doc-backlink" href="#r1">↩</a></p></li>`
    + `<li id="x1"><p class="x"><span class="xt">2 Цар 15:12</span></p></li>`);
  assert.deepStrictEqual(psalm, [
    { chapter: 3, verse: 2, text: "Господи! как умножились враги мои!\nмногие восстают на меня", footnotes: ["Или: противники."], paragraphStart: true },
    { chapter: 3, verse: 3, text: "Многие говорят.", footnotes: [], paragraphStart: true },
    { chapter: 3, verse: 4, verseEnd: 5, text: "Но Ты, Господи.", footnotes: [], paragraphStart: false },
    { chapter: 3, verse: 6, text: "Ложусь я.", footnotes: [], paragraphStart: false },
  ]);

  // The whole file: recognized by the Aleph identifier, books from the table of contents, other books skipped.
  const createDbsEpub = async ({ identifier = "bibles.dbs.org.aleph.RUSSGOS", creator = "Digital Bible Society" } = {}) => {
    const zip = new JSZip();
    zip.file("mimetype", "application/epub+zip");
    zip.file("META-INF/container.xml", `<?xml version="1.0"?><container xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="content/bible.opf" media-type="application/oebps-package+xml"/></rootfiles></container>`);
    const files = ["title_page.xhtml", "nav.xhtml", "chapters/MAT.xhtml", "chapters/MAT1.xhtml", "chapters/MAT2.xhtml", "chapters/TOB1.xhtml", "chapters/JUD1.xhtml"];
    const manifest = files.map((href, index) => `<item id="f${index}" href="${href}" media-type="application/xhtml+xml"/>`).join("");
    const spine = files.map((_href, index) => `<itemref idref="f${index}"/>`).join("");
    zip.file("content/bible.opf", `<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" version="3.0"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="uid">${identifier}</dc:identifier><dc:language>rus-RU</dc:language><dc:title>Синодальный перевод</dc:title><dc:title>The Russian Synodal Bible</dc:title><dc:creator>${creator}</dc:creator></metadata><manifest>${manifest}</manifest><spine>${spine}</spine></package>`);
    zip.file("content/title_page.xhtml", xhtml("Title", "<h1>Синодальный перевод</h1>"));
    zip.file("content/nav.xhtml", xhtml("ToC", `<nav epub:type="toc" id="toc"><ol><li><a href="chapters/MAT1.xhtml" class="book-title">Евангелие от Матфея</a><ol class="chapters"><li><a href="chapters/MAT1.xhtml">1</a></li></ol></li><li><a href="chapters/TOB1.xhtml" class="book-title">Товит</a></li></ol></nav>`));
    zip.file("content/chapters/MAT.xhtml", xhtml("Bible | Евангелие от Матфея", `<nav class="landmarks"><h1>Евангелие от Матфея</h1><a href="MAT1.xhtml">1</a></nav>`));
    zip.file("content/chapters/MAT1.xhtml", xhtml("Bible | Евангелие от Матфея 1", chapter(1, `${verse("MAT1", 1)} Родословие Иисуса Христа.`)));
    zip.file("content/chapters/MAT2.xhtml", xhtml("Bible | Евангелие от Матфея 2", chapter(2, `${verse("MAT2", 1)} Когда же Иисус родился.`)));
    zip.file("content/chapters/TOB1.xhtml", xhtml("Bible | Товит 1", chapter(1, `${verse("TOB1", 1)} Книга слов Товита.`)));
    zip.file("content/chapters/JUD1.xhtml", xhtml("Bible | Послание Иуды 1", chapter(1, `${verse("JUD1", 1)} Иуда, раб Иисуса Христа.`)));
    return zip.generateAsync({ type: "arraybuffer" });
  };

  const content = await createDbsEpub();
  const source = new DbsEpubBibleSource();
  assert.strictEqual((await selectBibleSource(createBibleSources(), { fileName: "RUSSGOS.epub", content })).id, "dbs-epub");
  assert.strictEqual(await source.canHandle({ fileName: "other.epub", content: await createDbsEpub({ identifier: "urn:uuid:1", creator: "Someone" }) }), false);
  assert.strictEqual(await source.canHandle({ fileName: "by-creator.epub", content: await createDbsEpub({ identifier: "urn:uuid:1" }) }), true);
  assert.deepStrictEqual(await source.readMetadata(content), { title: "Синодальный перевод", language: "ru" });

  const result = await source.importBible({ fileName: "RUSSGOS.epub", content, translationId: "ru-syn", translationName: "", language: "" });
  const translation = result.bibleIndexV2Data.translations["ru-syn"];
  assert.strictEqual(translation.language, "ru");
  assert.strictEqual(translation.name, "Синодальный перевод");
  assert.deepStrictEqual(translation.bookOrder, [40, 65]);
  // A book missing from the table of contents takes its name from the chapter page title.
  assert.deepStrictEqual(result.books.map((book) => [book.id, book.name, book.abbreviation]), [
    [40, "Евангелие от Матфея", "Мф"], [65, "Послание Иуды", "Иуд"],
  ]);
  assert(result.warnings.includes("Skipped books outside the 66-book canon: TOB"), "skipped books warning");
  assert.strictEqual(result.report.chapters, 3);
  assert.strictEqual(result.report.verses, 3);

  // The HTML archive (html_<ID>.zip): a page per book with every chapter, verse ids naming the chapter,
  // books in the order of the index page, the language guessed from the book names.
  const page = (title, main) => `<!DOCTYPE HTML><html><head><meta http-equiv="Content-Type" content="text/html; charset=utf-8"><meta name="generator" content="Aleph 1.0"><title>${title}</title></head><body><div id="nav"><a href="PSA.html#c1">1</a></div><main>${main}</main></body></html>`;
  const archiveVerse = (code, chapterNumber, number) => `<sup data-id="${code}_${chapterNumber}_${number}" class="v">${number}</sup>`;
  assert.deepStrictEqual(extractVersesFromAlephDocument(parseHtmlDocument(page("Псалтирь", `<b id="c1" class="c">1</b><p class="q1">${archiveVerse("PSA", 1, 1)} Блажен муж,
      который не ходит</p><p class="q1">${archiveVerse("PSA", 1, 2)} но в законе Господа</p><b id="c2" class="c">2</b><p class="d">Псалом Давида.</p>`
    + `<p class="p">${archiveVerse("PSA", 2, 1)} Зачем мятутся народы? ${archiveVerse("PSA", 2, "2-3")} Восстают цари.</p>`)), 0), [
    { chapter: 1, verse: 1, text: "Блажен муж, который не ходит", footnotes: [], paragraphStart: true },
    { chapter: 1, verse: 2, text: "но в законе Господа", footnotes: [], paragraphStart: true },
    { chapter: 2, verse: 1, text: "Зачем мятутся народы?", footnotes: [], paragraphStart: true, heading: "Псалом Давида." },
    { chapter: 2, verse: 2, verseEnd: 3, text: "Восстают цари.", footnotes: [], paragraphStart: false },
  ]);

  const createArchive = async ({ generator = "Aleph 1.0" } = {}) => {
    const zip = new JSZip();
    zip.file("html/index.html", `<!DOCTYPE HTML><html><head><title></title><meta name="generator" content="Aletheia 1.0"></head><body class="title-page"><h1></h1><ul>`
      + `<li><a href="books/MAT.html">Евангелие от Матфея</a></li><li><a href="books/JAS.html">Послание Иакова</a></li><li><a href="books/ROM.html">Послание к Римлянам</a></li></ul></body></html>`);
    zip.file("html/_/aleph.css", "p {}");
    zip.file("html/books/ROM.html", page("Послание к Римлянам", `<b id="c1" class="c">1</b><p class="p">${archiveVerse("ROM", 1, 1)} Павел, раб Иисуса Христа.</p>`).replace("Aleph 1.0", generator));
    zip.file("html/books/MAT.html", page("Евангелие от Матфея", `<b id="c1" class="c">1</b><p class="p">${archiveVerse("MAT", 1, 1)} Родословие Иисуса Христа.</p>`).replace("Aleph 1.0", generator));
    zip.file("html/books/JAS.html", page("Послание Иакова", `<b id="c1" class="c">1</b><p class="p">${archiveVerse("JAS", 1, 1)} Иаков, раб Бога.</p>`).replace("Aleph 1.0", generator));
    zip.file("html/books/TOB.html", page("Товит", `<b id="c1" class="c">1</b><p class="p">${archiveVerse("TOB", 1, 1)} Книга слов Товита.</p>`).replace("Aleph 1.0", generator));
    return zip.generateAsync({ type: "arraybuffer" });
  };

  const archive = await createArchive();
  const archiveSource = new DbsHtmlArchiveBibleSource();
  assert.strictEqual((await selectBibleSource(createBibleSources(), { fileName: "html_RUSS76.zip", content: archive })).id, "dbs-html-archive");
  assert.strictEqual(await archiveSource.canHandle({ fileName: "other.zip", content: await createArchive({ generator: "Other" }) }), false);
  assert.deepStrictEqual(await archiveSource.readMetadata(archive), { title: null, language: "ru" });

  const archiveResult = await archiveSource.importBible({ fileName: "html_RUSS76.zip", content: archive, translationId: "ru-syn", translationName: "", language: "" });
  const archiveTranslation = archiveResult.bibleIndexV2Data.translations["ru-syn"];
  assert.strictEqual(archiveTranslation.name, "RUSS76");
  assert.strictEqual(archiveTranslation.language, "ru");
  assert.deepStrictEqual(archiveTranslation.bookOrder, [40, 59, 45]);
  assert.deepStrictEqual(archiveResult.books.map((book) => [book.id, book.abbreviation]), [[40, "Мф"], [59, "Иак"], [45, "Рим"]]);
  assert(archiveResult.warnings.includes("Skipped books outside the 66-book canon: TOB"), "skipped archive books warning");
};
